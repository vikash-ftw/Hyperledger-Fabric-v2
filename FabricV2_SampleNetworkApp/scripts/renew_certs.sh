echo "Restarting ca_orderer container..."
docker restart ca_orderer
echo "Renewing orderers certs..."
sleep 2
renewOrderer

## renew certs for org1
echo
echo "Removing tls-cert.pem in fabric-ca/org1/ ..."
sudo rm ${PWD}/organizations/fabric-ca/org1/tls-cert.pem
echo "Restarting ca_org1 container..."
docker restart ca_org1
echo "Renewing org1 certs..."
sleep 2
renewOrg1

## restart all containers
echo
echo "Restarting network ..."
sleep 2
${PWD}/scripts/restart_network.sh
sleep 2

echo
echo "========= Renewed the certs for peers and orderers =========== "

echo
